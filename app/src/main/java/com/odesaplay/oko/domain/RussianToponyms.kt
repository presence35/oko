    /** The Russian display form for a city's Ukrainian name, or the UA original if unknown. */
    fun city(nameUa: String): String = CITY_RU[norm(nameUa)] ?: nameUa

    /** The Russian display form for a canonical oblast ID, or the ID if unknown. */
    fun oblast(id: String): String = OBLAST_RU[id] ?: id

    /**
     * The Russian display form for a raion name — explicit override when known, else the
     * regular Ukrainian→Russian adjectival rule. Never used for matching.
     */
    fun raion(nameUa: String): String {
        val raw = norm(nameUa)
        val n = raw.lowercase()
        RAION_RU[n]?.let { return it }
        val hasSuffix = n.contains("район") || n.contains("р-н")
        val base = n.removeSuffix(" район").removeSuffix(" р-н").trim()
        if (base.isEmpty()) return raw
        RAION_RU[base]?.let { return if (hasSuffix) "$it район" else it }
        val ruled = raionByRule(base) ?: return raw
        return if (hasSuffix) "$ruled район" else ruled
    }

    /** Regular adjectival suffix rule, or null when nothing changed (unknown word). */
    private fun raionByRule(base: String): String? {
        val out = base
            .replace("ський", "ский")
            .replace("цький", "цкий")
            .replace("зький", "зкий")
            .replace("ська", "ская")
            .replace("ське", "ское")
            .replace("ний", "ный")
            .replace("ій", "ий")
            .replace("і", "и")
            .replace("ї", "и")
            .replace("є", "е")
        if (out == base) return null
        return out.replaceFirstChar { it.uppercase() }
    }
